function New-ProbeSerialFixture {
    param([ValidateSet('Meshtastic', 'MeshCore', 'Text', 'Silent')][string]$Protocol,
        [byte[]]$Reply = @(), [int]$ChunkSize = 3)
    $port = [pscustomobject]@{
        IsOpen = $true
        Protocol = $Protocol
        Reply = $Reply
        ChunkSize = $ChunkSize
        Incoming = (New-Object 'System.Collections.Generic.List[byte]')
        Writes = (New-Object 'System.Collections.Generic.List[object]')
        TextInput = ''
        SuppressVersion = $false
        Closed = 0
        Disposed = 0
    }
    $port | Add-Member ScriptProperty BytesToRead { return $this.Incoming.Count }
    $port | Add-Member ScriptMethod DiscardInBuffer { $this.Incoming.Clear() }
    $port | Add-Member ScriptMethod Write {
        param([byte[]]$Bytes, [int]$Offset, [int]$Count)
        $slice = New-Object byte[] $Count
        [Array]::Copy($Bytes, $Offset, $slice, 0, $Count)
        $this.Writes.Add($slice)
        if ($this.Protocol -eq 'Meshtastic' -and $Count -ge 8 -and $slice[0] -eq 0x94 -and
            $slice[1] -eq 0xc3 -and $slice[4] -eq 0x18) {
            $this.Incoming.AddRange([byte[]]$this.Reply)
        }
        if ($this.Protocol -eq 'MeshCore' -and $Count -eq 5 -and $slice[0] -eq 0x3c -and $slice[3] -eq 0x16) {
            $this.Incoming.AddRange([byte[]]$this.Reply)
        }
    }
    $port | Add-Member ScriptMethod Read {
        param([byte[]]$Buffer, [int]$Offset, [int]$Count)
        $read = [Math]::Min([Math]::Min($Count, $this.ChunkSize), $this.Incoming.Count)
        for ($index = 0; $index -lt $read; $index++) { $Buffer[$Offset + $index] = $this.Incoming[$index] }
        if ($read) { $this.Incoming.RemoveRange(0, $read) }
        return $read
    }
    $port | Add-Member ScriptMethod WriteLine {
        param([string]$Text)
        $this.Writes.Add($Text)
        if ($this.Protocol -ne 'Text') { return }
        # A CommonCLI record requires CR. Simulate leftover binary bytes before
        # the first query so detection has to clear the parser first.
        $this.TextInput += $Text + "`r"
        foreach ($record in @($this.TextInput -split "`r")) {
            if ($record -eq 'board') { $this.Incoming.AddRange([Text.Encoding]::ASCII.GetBytes("board`r`n-> RAK4631`r`n")) }
            elseif (($record -eq 'ver' -or $record -eq 'version') -and -not $this.SuppressVersion) {
                $this.Incoming.AddRange([Text.Encoding]::ASCII.GetBytes("$record`r`n-> v1.18.0.1`r`n"))
            }
            elseif ($record -eq 'get name') { $this.Incoming.AddRange([Text.Encoding]::ASCII.GetBytes("get name`r`n-> fixture repeater`r`n")) }
        }
        $this.TextInput = ''
    }
    $port | Add-Member ScriptMethod ReadExisting {
        $read = [Math]::Min($this.ChunkSize, $this.Incoming.Count)
        [byte[]]$bytes = @($this.Incoming.GetRange(0, $read))
        if ($read) { $this.Incoming.RemoveRange(0, $read) }
        return [Text.Encoding]::ASCII.GetString($bytes)
    }
    $port | Add-Member ScriptMethod Close { $this.Closed++; $this.IsOpen = $false }
    $port | Add-Member ScriptMethod Dispose { $this.Disposed++; $this.IsOpen = $false }
    return $port
}

# Noise and an unrelated frame precede the two actual replies. Each read
# returns only three bytes, splitting both framing headers and protobuf data.
[byte[]]$replies = ([Text.Encoding]::ASCII.GetBytes("INFO: MT firmware boot`r`n")) +
    # A plausible but incomplete noise frame must not hide a later real frame.
    [byte[]]@(0x94, 0xc3, 0x01, 0x00, 0x00) +
    (New-MeshtasticFrame (Convert-HexBytes '30 01')) +
    (New-MeshtasticFrame $myInfoPayload) + (New-MeshtasticFrame $metadataPayload)
$port = New-ProbeSerialFixture -Protocol Meshtastic -Reply $replies
$identity = Invoke-MeshtasticInfoProbe -SerialPort $port -TotalMs 750
Assert-True ($null -ne $identity) 'Fragmented MT identity reply was missed.'
Assert-Equal 'seeed_xiao_nrf52_kit' $identity.Board 'MT stream lost the board field.'
Assert-Equal '2.7.4.abc123' $identity.Version 'MT stream lost the metadata version.'
$disconnectWrites = @($port.Writes | Where-Object {
    $_ -is [byte[]] -and $_.Length -eq 6 -and $_[0] -eq 0x94 -and $_[4] -eq 0x20 -and $_[5] -eq 1
})
Assert-Equal 1 $disconnectWrites.Count 'Confirmed MT probe did not end its protocol session.'
Assert-Equal 3 $port.Writes.Count 'MT identification sent commands beyond wake, config query, and disconnect.'

$port = New-ProbeSerialFixture -Protocol Meshtastic -Reply (New-MeshtasticFrame (Convert-HexBytes '1a 00'))
