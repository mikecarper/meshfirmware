# Descriptors and remembered detection choose the query order, never skip the
# actual handshake. Cache keys follow the physical serial, not a recycled COM.
$script:FirmwareProtocolHints = @{ 'remembered-mt' = 'Meshtastic'; 'remembered-mc' = 'MeshCore' }
$order = @(& $productionProbeOrder -UsbIdentity ([pscustomobject]@{
    SerialNumber = 'REMEMBERED-MT'; BusReportedDescription = ''
}))
Assert-Equal 'Meshtastic' $order[0] 'Last successful detection did not choose MT first.'
Assert-Equal 2 $order.Count 'Protocol hint removed the alternative handshake.'
$order = @(& $productionProbeOrder -UsbIdentity ([pscustomobject]@{
    SerialNumber = 'remembered-mt'; BusReportedDescription = 'MeshCore Full Companion'
}))
Assert-Equal 'MeshCore' $order[0] 'Fresh MC descriptor did not choose MC first.'
$order = @(& $productionProbeOrder -UsbIdentity ([pscustomobject]@{
    SerialNumber = 'a-different-radio'; BusReportedDescription = ''
}))
Assert-Equal 2 $order.Count 'An unknown USB serial was restricted to one protocol.'

