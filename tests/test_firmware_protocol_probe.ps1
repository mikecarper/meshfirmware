function Convert-HexBytes {
    param([string]$Hex)
    return ,([byte[]]@($Hex.Trim() -split '\s+' | ForEach-Object { [Convert]::ToByte($_, 16) }))
}
function New-MeshtasticFrame {
    param([byte[]]$Payload)
    return ,([byte[]](@(0x94, 0xc3, ($Payload.Length -shr 8), ($Payload.Length -band 0xff)) + $Payload))
}

