$ErrorActionPreference = 'Stop'
$tokens = $null
$parseErrors = $null
$firmwarePath = Join-Path (Split-Path $PSScriptRoot -Parent) 'firmware.cmd'
$firmwareAst = [System.Management.Automation.Language.Parser]::ParseFile(
    $firmwarePath, [ref]$tokens, [ref]$parseErrors)
if ($parseErrors.Count) { throw "firmware.cmd parse failed: $parseErrors" }

function Assert-True {
    param([bool]$Condition, [string]$Message)
    if (-not $Condition) { throw $Message }
}
function Assert-Equal {
    param($Expected, $Actual, [string]$Message)
    if ($Expected -ne $Actual) { throw "$Message Expected '$Expected', got '$Actual'." }
}
function Assert-Throws {
    param([scriptblock]$Action, [string]$Message)
    $thrown = $false
    try { $null = & $Action } catch { $thrown = $true }
    Assert-True $thrown $Message
}
foreach ($functionName in @(
    'Remove-Ansi', 'Strip-Prefix', 'Test-IsLogLine', 'Get-VersionTokenFromText',
    'Get-UsableSerialResponse', 'Read-ProtobufVarint', 'ConvertFrom-ProtobufMessage',
    'Get-MeshtasticIdentityFromPayload', 'Invoke-MeshtasticInfoProbe',
    'Read-QuickSerialResponse', 'Get-MeshCoreTextInfoProbe',
    'Get-QuickFirmwareNodeInfo', 'Get-UsbNodeInfo', 'Invoke-MeshCoreBinaryCommand',
    'Get-MeshCoreCompanionInfo', 'Get-FirmwareProbeOrder'
)) {
    $definition = $firmwareAst.Find({ param($node)
        $node -is [System.Management.Automation.Language.FunctionDefinitionAst] -and
        $node.Name -eq $functionName
    }, $true)
    if ($null -eq $definition) { throw "Missing function under test: $functionName" }
    Invoke-Expression $definition.Extent.Text
}
